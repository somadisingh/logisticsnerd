-- Minimal supplier cash accounts: one currency, append-only money events.
-- Balances are derived from money_ledger, never stored.
CREATE TABLE supplier_payments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_id bigint NOT NULL REFERENCES core_bindings(id),
 _supplier_kind text GENERATED ALWAYS AS ('supplier'::text) STORED,
 amount_minor bigint NOT NULL CHECK(amount_minor>0),
 currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 paid_on date NOT NULL,
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT supplier_payment_kind_fk FOREIGN KEY(supplier_id,_supplier_kind) REFERENCES core_bindings(id,kind)
);
CREATE TABLE money_ledger (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_type text NOT NULL CHECK(entry_type IN ('supplier_charge','supplier_payment')),
 supplier_id bigint NOT NULL REFERENCES core_bindings(id),
 _supplier_kind text GENERATED ALWAYS AS ('supplier'::text) STORED,
 amount_minor bigint NOT NULL CHECK(amount_minor>=0),
 currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 occurred_on date NOT NULL,
 po_line_id bigint REFERENCES purchase_order_lines(id),
 receipt_line_id bigint UNIQUE REFERENCES receipt_lines(id),
 payment_id bigint UNIQUE REFERENCES supplier_payments(id),
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT money_supplier_kind_fk FOREIGN KEY(supplier_id,_supplier_kind) REFERENCES core_bindings(id,kind),
 -- A charge comes from exactly one receipt line of one PO line; a payment from one payment.
 CHECK((entry_type='supplier_charge')=(receipt_line_id IS NOT NULL AND po_line_id IS NOT NULL AND payment_id IS NULL)),
 CHECK((entry_type='supplier_payment')=(payment_id IS NOT NULL AND receipt_line_id IS NULL AND po_line_id IS NULL)),
 CHECK(entry_type<>'supplier_payment' OR amount_minor>0)
);
CREATE INDEX money_ledger_supplier ON money_ledger(supplier_id);
CREATE INDEX money_ledger_po_line ON money_ledger(po_line_id);

-- Every money write and every business-currency write takes the same ledger
-- lock last, so the single-currency and overpayment checks cannot race.
CREATE FUNCTION money_currency() RETURNS text LANGUAGE sql STABLE SET search_path=logistics,pg_temp AS $$
 SELECT COALESCE((SELECT currency FROM business_setup WHERE singleton),
                 (SELECT currency FROM money_ledger ORDER BY id LIMIT 1));
$$;
CREATE FUNCTION guard_money_entry() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE expected text; p purchase_order_lines%ROWTYPE; po purchase_orders%ROWTYPE; rl receipt_lines%ROWTYPE;
 rc receipts%ROWTYPE; pay supplier_payments%ROWTYPE; line_total numeric; line_quantity numeric;
 received bigint; charged bigint; owed bigint;
BEGIN
 PERFORM pg_advisory_xact_lock(1768842364,0);
 expected:=money_currency();
 IF expected IS NOT NULL AND NEW.currency<>expected THEN RAISE EXCEPTION 'money currency must match the business currency' USING ERRCODE='23514'; END IF;
 IF NEW.entry_type='supplier_charge' THEN
  SELECT * INTO p FROM purchase_order_lines WHERE id=NEW.po_line_id FOR UPDATE;
  SELECT * INTO po FROM purchase_orders WHERE id=p.purchase_order_id;
  SELECT * INTO rl FROM receipt_lines WHERE id=NEW.receipt_line_id;
  SELECT * INTO rc FROM receipts WHERE id=rl.receipt_id;
  IF rl.po_line_id IS DISTINCT FROM NEW.po_line_id OR po.status<>'approved' OR po.supplier_id<>NEW.supplier_id
   OR po.currency<>NEW.currency OR rc.request_key<>NEW.request_key OR rc.received_on<>NEW.occurred_on THEN
   RAISE EXCEPTION 'supplier charge must match its approved purchase line and receipt' USING ERRCODE='23514';
  END IF;
  line_total:=(p.approved_terms->>'total_minor')::numeric;
  line_quantity:=(p.approved_terms->>'quantity')::numeric;
  IF line_total IS NULL OR line_quantity IS DISTINCT FROM p.quantity THEN RAISE EXCEPTION 'purchase line has no frozen approved total' USING ERRCODE='23514'; END IF;
  -- Cumulative rounding: partial charges always sum exactly to the frozen line total.
  SELECT COALESCE(sum(quantity),0)::bigint INTO received FROM receipt_lines WHERE po_line_id=NEW.po_line_id AND id<=NEW.receipt_line_id;
  SELECT COALESCE(sum(amount_minor),0)::bigint INTO charged FROM money_ledger WHERE po_line_id=NEW.po_line_id;
  IF NEW.amount_minor<>floor(line_total*received/line_quantity)::bigint-charged THEN RAISE EXCEPTION 'supplier charge must follow the approved line total' USING ERRCODE='23514'; END IF;
 ELSE
  SELECT * INTO pay FROM supplier_payments WHERE id=NEW.payment_id;
  IF (pay.supplier_id,pay.amount_minor,pay.currency,pay.paid_on,pay.request_key) IS DISTINCT FROM
     (NEW.supplier_id,NEW.amount_minor,NEW.currency,NEW.occurred_on,NEW.request_key) THEN
   RAISE EXCEPTION 'ledger payment must match its payment record' USING ERRCODE='23514';
  END IF;
  -- Supplier revisions share an external key; the account follows the supplier, not the revision.
  SELECT COALESCE(sum(CASE WHEN m.entry_type='supplier_charge' THEN m.amount_minor ELSE -m.amount_minor END),0)::bigint INTO owed
   FROM money_ledger m JOIN core_bindings b ON b.id=m.supplier_id
   WHERE b.kind='supplier' AND b.external_key=(SELECT external_key FROM core_bindings WHERE id=NEW.supplier_id);
  IF NEW.amount_minor>owed THEN RAISE EXCEPTION 'payment exceeds the amount owed to the supplier' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER money_entry_guard BEFORE INSERT ON money_ledger FOR EACH ROW EXECUTE FUNCTION guard_money_entry();

-- Deferred: stock and money for a purchase receipt commit together or not at all.
CREATE FUNCTION check_receipt_charge() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 IF NEW.po_line_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM money_ledger m JOIN receipt_lines r ON r.id=m.receipt_line_id
   WHERE r.receipt_id=NEW.receipt_id AND m.po_line_id=NEW.po_line_id AND m.receipt_line_id>=NEW.id) THEN
  RAISE EXCEPTION 'purchase receipt must record its supplier charge' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER receipt_charge_check AFTER INSERT ON receipt_lines DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_receipt_charge();
CREATE FUNCTION check_payment_entry() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM money_ledger WHERE payment_id=NEW.id) THEN RAISE EXCEPTION 'supplier payment must have its ledger entry' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER payment_entry_check AFTER INSERT ON supplier_payments DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_payment_entry();

-- One currency: the business currency cannot diverge from recorded money.
CREATE FUNCTION guard_business_currency() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(1768842364,0);
 IF EXISTS(SELECT 1 FROM money_ledger WHERE currency<>NEW.currency) THEN RAISE EXCEPTION 'business currency cannot differ from recorded money' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER business_currency_guard BEFORE INSERT OR UPDATE OF currency ON business_setup FOR EACH ROW EXECUTE FUNCTION guard_business_currency();

CREATE TRIGGER immutable_rows BEFORE UPDATE OR DELETE ON money_ledger FOR EACH ROW EXECUTE FUNCTION reject_mutation();
CREATE TRIGGER immutable_rows BEFORE UPDATE OR DELETE ON supplier_payments FOR EACH ROW EXECUTE FUNCTION reject_mutation();

